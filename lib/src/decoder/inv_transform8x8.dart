/// An inverse-scanned 8x8 scaling matrix in row-major raster order.
///
/// [flat] is the `Flat_8x8_16` matrix inferred when scaling-matrix syntax is
/// absent. [defaultIntra] and [defaultInter] are the Table 7-4 defaults used by
/// the scaling-list fallback rules. A parsed scaling list can be passed to
/// [H264ScalingMatrix8x8.fromScalingList] in its native scan order.
final class H264ScalingMatrix8x8 {
  const H264ScalingMatrix8x8._(this.rasterValues);

  factory H264ScalingMatrix8x8.fromScalingList(List<int> scalingList) {
    _validateScalingValues(scalingList, 'scalingList');
    return H264ScalingMatrix8x8._(
      List<int>.unmodifiable(inverseScan8x8(scalingList)),
    );
  }

  factory H264ScalingMatrix8x8.fromRaster(List<int> rasterValues) {
    _validateScalingValues(rasterValues, 'rasterValues');
    return H264ScalingMatrix8x8._(List<int>.unmodifiable(rasterValues));
  }

  static const H264ScalingMatrix8x8 flat = H264ScalingMatrix8x8._(
    _flatScalingMatrix8x8,
  );

  static const H264ScalingMatrix8x8 defaultIntra = H264ScalingMatrix8x8._(
    _defaultIntraScalingMatrix8x8,
  );

  static const H264ScalingMatrix8x8 defaultInter = H264ScalingMatrix8x8._(
    _defaultInterScalingMatrix8x8,
  );

  /// 64 scaling weights in row-major 8x8 raster order.
  final List<int> rasterValues;

  int weightAt(int row, int column) {
    RangeError.checkValueInInterval(row, 0, 7, 'row');
    RangeError.checkValueInInterval(column, 0, 7, 'column');
    return rasterValues[row * 8 + column];
  }
}

/// Maps exactly 64 scan-order values into a row-major 8x8 raster block.
List<int> inverseScan8x8(
  List<int> scannedValues, {
  H264ScanOrder8x8 scanOrder = H264ScanOrder8x8.frame,
}) {
  _requireBlock(scannedValues, 'scannedValues');
  final scan = switch (scanOrder) {
    H264ScanOrder8x8.frame => h264FrameScan8x8,
    H264ScanOrder8x8.field => h264FieldScan8x8,
  };
  final raster = List<int>.filled(64, 0);
  for (var scanIndex = 0; scanIndex < 64; scanIndex++) {
    raster[scan[scanIndex]] = scannedValues[scanIndex];
  }
  return raster;
}

/// Applies H.264 8x8 inverse coefficient scaling (8-bit QP range).
///
/// [coefficients] and [scalingMatrix] are both in row-major raster order. This
/// implements the two QP branches in section 8.5.13.1, including the specified
/// rounding before a right shift for QP values below 36.
List<int> inverseQuantize8x8(
  List<int> coefficients, {
  required int qp,
  H264ScalingMatrix8x8 scalingMatrix = H264ScalingMatrix8x8.flat,
}) {
  _requireBlock(coefficients, 'coefficients');
  RangeError.checkValueInInterval(qp, 0, 51, 'qp');

  final qpDiv6 = qp ~/ 6;
  final qpMod6 = qp % 6;
  final scaled = List<int>.filled(64, 0);
  for (var index = 0; index < 64; index++) {
    final product =
        coefficients[index] *
        scalingMatrix.rasterValues[index] *
        _normAdjust8x8[qpMod6][index];
    if (qpDiv6 >= 6) {
      scaled[index] = product << (qpDiv6 - 6);
    } else {
      scaled[index] = (product + (1 << (5 - qpDiv6))) >> (6 - qpDiv6);
    }
  }
  return scaled;
}

/// Applies the separable H.264 8x8 inverse integer transform.
///
/// Input coefficients are already inverse-quantized and in row-major raster
/// order. The returned residual samples include the normative `(m + 32) >> 6`
/// normalization.
List<int> inverseIntegerTransform8x8(List<int> scaledCoefficients) {
  _requireBlock(scaledCoefficients, 'scaledCoefficients');

  final horizontal = List<int>.filled(64, 0);
  for (var row = 0; row < 8; row++) {
    final offset = row * 8;
    final transformed = _inverseTransform1d8x8(
      List<int>.generate(8, (column) => scaledCoefficients[offset + column]),
    );
    for (var column = 0; column < 8; column++) {
      horizontal[offset + column] = transformed[column];
    }
  }

  final residual = List<int>.filled(64, 0);
  for (var column = 0; column < 8; column++) {
    final transformed = _inverseTransform1d8x8(
      List<int>.generate(8, (row) => horizontal[row * 8 + column]),
    );
    for (var row = 0; row < 8; row++) {
      residual[row * 8 + column] = (transformed[row] + 32) >> 6;
    }
  }
  return residual;
}

/// Inverse-quantizes and inverse-transforms one raster-order 8x8 block.
List<int> invTransform8x8(
  List<int> coefficients, {
  int qp = 26,
  H264ScalingMatrix8x8 scalingMatrix = H264ScalingMatrix8x8.flat,
}) => inverseIntegerTransform8x8(
  inverseQuantize8x8(coefficients, qp: qp, scalingMatrix: scalingMatrix),
);

List<int> _inverseTransform1d8x8(List<int> values) {
  final e0 = values[0] + values[4];
  final e1 = -values[3] + values[5] - values[7] - (values[7] >> 1);
  final e2 = values[0] - values[4];
  final e3 = values[1] + values[7] - values[3] - (values[3] >> 1);
  final e4 = (values[2] >> 1) - values[6];
  final e5 = -values[1] + values[7] + values[5] + (values[5] >> 1);
  final e6 = values[2] + (values[6] >> 1);
  final e7 = values[3] + values[5] + values[1] + (values[1] >> 1);

  final f0 = e0 + e6;
  final f1 = e1 + (e7 >> 2);
  final f2 = e2 + e4;
  final f3 = e3 + (e5 >> 2);
  final f4 = e2 - e4;
  final f5 = (e3 >> 2) - e5;
  final f6 = e0 - e6;
  final f7 = e7 - (e1 >> 2);

  return <int>[
    f0 + f7,
    f2 + f5,
    f4 + f3,
    f6 + f1,
    f6 - f1,
    f4 - f3,
    f2 - f5,
    f0 - f7,
  ];
}

void _requireBlock(List<int> values, String name) {
  if (values.length != 64) {
    throw ArgumentError.value(
      values.length,
      name,
      'must contain exactly 64 values',
    );
  }
}

void _validateScalingValues(List<int> values, String name) {
  _requireBlock(values, name);
  for (var index = 0; index < values.length; index++) {
    final value = values[index];
    if (value < 1 || value > 255) {
      throw RangeError.range(value, 1, 255, '$name[$index]');
    }
  }
}

